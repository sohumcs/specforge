import { render, screen } from '@testing-library/react'
import { describe, expect, it } from 'vitest'

import type { Job } from '../lib/types'
import { JobProgress } from './JobProgress'
import { ErrorState, ProviderBadge, ScoreGauge } from './ui'
import { ApiError } from '../lib/api'

const job = (over: Partial<Job>): Job => ({
  job_id: 'j', blueprint_id: 'b', kind: 'generate', status: 'running', step: 'generating_design', progress: 40, result: null, error: null, ...over,
})

describe('ScoreGauge', () => {
  it('announces the score', () => {
    render(<ScoreGauge score={87} />)
    expect(screen.getByLabelText('Quality score 87 out of 100')).toBeInTheDocument()
  })
  it('handles an unscored blueprint', () => {
    render(<ScoreGauge score={null} />)
    expect(screen.getByLabelText('Not scored yet')).toBeInTheDocument()
  })
})

describe('ProviderBadge', () => {
  it.each([
    ['gemini', /Generated by gemini/],
    ['gemini+groq', /Generated by gemini\+groq/],
    ['demo', /offline generator/],
    ['cache', /generation cache/],
  ])('%s', (provider, title) => {
    render(<ProviderBadge provider={provider} />)
    expect(screen.getByText(provider, { exact: false })).toHaveAttribute('title', expect.stringMatching(title))
  })
  it('renders nothing without a provider', () => {
    const { container } = render(<ProviderBadge provider={null} />)
    expect(container).toBeEmptyDOMElement()
  })
})

describe('JobProgress', () => {
  it('marks finished, active and pending steps', () => {
    render(<JobProgress job={job({})} />)
    expect(screen.getByText('Parsing the brief').parentElement).toHaveTextContent('(done)')
    expect(screen.getAllByText('Designing modules, data & API').at(-1)!.parentElement).toHaveTextContent('(active)')
    expect(screen.getByText('Scoring').parentElement).toHaveTextContent('(todo)')
    expect(screen.getByText('40%')).toBeInTheDocument()
  })
  it('shows the provider badge and errors', () => {
    const { rerender } = render(<JobProgress job={job({ status: 'succeeded', step: 'done', progress: 100, result: { provider: 'groq' } })} />)
    expect(screen.getByTitle('Generated by groq')).toHaveTextContent('groq')
    rerender(<JobProgress job={job({ status: 'failed', error: { code: 'X', message: 'Generation failed unexpectedly' } })} />)
    expect(screen.getByRole('alert')).toHaveTextContent('Generation failed unexpectedly')
  })
})

describe('ErrorState', () => {
  it('shows the API error message and a retry', () => {
    render(<ErrorState error={new ApiError(503, 'QUEUE_UNAVAILABLE', 'The job queue is unavailable')} onRetry={() => {}} />)
    expect(screen.getByRole('alert')).toHaveTextContent('The job queue is unavailable')
    expect(screen.getByRole('button', { name: /try again/i })).toBeInTheDocument()
  })
})
