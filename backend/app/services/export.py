"""Blueprint export: JSON (machine), Markdown (humans, Git), PDF (stakeholders).

Markdown and PDF are built from the same section model, so they never drift.
PDF uses ReportLab (pure Python, BSD); see ADR-012 for why not WeasyPrint.
"""

import html
import io
import uuid
from dataclasses import dataclass, field
from datetime import UTC, datetime
from typing import Any

from sqlalchemy import select
from sqlalchemy.orm import Session

from app.models import Blueprint, QualityReport
from app.models.enums import EdgeType, NodeType
from app.services.verification import snapshot
from app.verify.graphview import GNode, GraphView

E, T = EdgeType, NodeType


@dataclass
class Section:
    title: str
    paragraphs: list[str] = field(default_factory=list)
    bullets: list[str] = field(default_factory=list)
    table: list[list[str]] = field(default_factory=list)  # first row = header


def _keys(g: GraphView, ids: list[uuid.UUID]) -> str:
    return ", ".join(sorted(g.nodes[i].key for i in ids)) or "-"


def build_sections(db: Session, bp: Blueprint) -> tuple[list[Section], dict[str, Any]]:
    g, _ = snapshot(db, bp.id)
    qr = db.scalar(
        select(QualityReport)
        .where(QualityReport.blueprint_id == bp.id)
        .order_by(QualityReport.created_at.desc())
    )
    secs: list[Section] = []

    overview = Section("Overview", paragraphs=[bp.brief])
    if qr is not None:
        cats = ", ".join(f"{c['category']} {c['score']}" for c in qr.breakdown["categories"])
        overview.paragraphs.append(f"Quality Score: {qr.score}/100 ({cats}).")
    overview.paragraphs.append(f"Generated by: {bp.provider or 'manual'} · version {bp.version}")
    secs.append(overview)

    reqs = Section("Requirements", table=[["Key", "Type", "Priority", "Requirement", "Stories"]])
    for r in g.of_type(T.requirement):
        kind = r.body.get("kind", "functional")
        if kind == "non_functional":
            kind = f"NFR ({r.body.get('nfr_category', '')})"
        reqs.table.append(
            [
                r.key,
                kind,
                str(r.body.get("priority", "")),
                f"{r.title}. {r.body.get('description', '')}".strip(),
                _keys(g, [e.dst for e in g.out(r.id, E.refines)]),
            ]
        )
    secs.append(reqs)

    stories = Section("User stories")
    for s in g.of_type(T.story):
        ac = "; ".join(str(x) for x in s.body.get("acceptance_criteria", []))
        stories.bullets.append(f"**{s.key}** {s.title}\n  Acceptance: {ac}")
    secs.append(stories)

    mods = Section("Modules", table=[["Key", "Module", "Responsibility", "Stories", "Depends on"]])
    for m in g.of_type(T.module):
        mods.table.append(
            [
                m.key,
                m.title,
                str(m.body.get("responsibility", "")),
                _keys(g, [e.src for e in g.inc(m.id, E.implemented_by)]),
                _keys(g, [e.dst for e in g.out(m.id, E.depends_on)]),
            ]
        )
    secs.append(mods)

    apis = Section("REST API", table=[["Key", "Endpoint", "Summary", "Module", "Entities"]])
    for a in g.of_type(T.api):
        apis.table.append(
            [
                a.key,
                a.title,
                str(a.body.get("summary", "")),
                _keys(g, [e.src for e in g.inc(a.id, E.exposes)]),
                _keys(g, [e.dst for e in g.out(a.id, E.persists)]),
            ]
        )
    secs.append(apis)

    ents = Section("Data model")
    for en in g.of_type(T.entity):
        fields = ", ".join(
            f"{f.get('name')}: {f.get('type')}{' (PK)' if f.get('primary_key') else ''}"
            for f in en.body.get("fields", [])
        )
        rels = ", ".join(
            f"{e.type.value} {g.nodes[e.dst].title}" for e in g.out(en.id, E.relates_to)
        )
        ents.bullets.append(
            f"**{en.title}** ({en.key}): {fields}" + (f"; relations: {rels}" if rels else "")
        )
    secs.append(ents)

    tests = Section("Test scenarios", table=[["Key", "Kind", "Scenario", "Verifies"]])
    for t in g.of_type(T.test):
        tests.table.append(
            [
                t.key,
                str(t.body.get("kind", "")),
                t.title,
                _keys(g, [e.src for e in g.inc(t.id, E.verified_by)]),
            ]
        )
    secs.append(tests)

    risks = Section("Risk register", table=[["Key", "Risk", "L / I", "Mitigation", "Threatens"]])
    for k in g.of_type(T.risk):
        risks.table.append(
            [
                k.key,
                k.title,
                f"{k.body.get('likelihood')}/{k.body.get('impact')}",
                str(k.body.get("mitigation", "")),
                _keys(g, [e.dst for e in g.out(k.id, E.threatens)]),
            ]
        )
    secs.append(risks)

    if qr is not None:
        issues = Section(
            "Open quality issues",
            bullets=[
                f"[{i.severity.value}] {i.rule_code}: {i.message}"
                for i in qr.issues
                if not i.resolved
            ],
        )
        if not issues.bullets:
            issues.paragraphs.append("None.")
        secs.append(issues)

    data = {
        "blueprint": {
            "id": str(bp.id),
            "title": bp.title,
            "brief": bp.brief,
            "version": bp.version,
            "provider": bp.provider,
            "quality_score": bp.quality_score,
        },
        "nodes": [_node_json(n) for n in sorted(g.nodes.values(), key=lambda n: n.position)],
        "edges": [
            {"src": g.nodes[e.src].key, "dst": g.nodes[e.dst].key, "type": e.type.value}
            for e in g.edges
        ],
        "quality": None
        if qr is None
        else {
            "score": qr.score,
            "breakdown": qr.breakdown,
            "issues": [
                {
                    "rule": i.rule_code,
                    "severity": i.severity.value,
                    "message": i.message,
                    "resolved": i.resolved,
                }
                for i in qr.issues
            ],
        },
        "exported_at": datetime.now(UTC).isoformat(),
    }
    return secs, data


def _node_json(n: GNode) -> dict[str, Any]:
    return {"key": n.key, "type": n.type.value, "title": n.title, "body": n.body}


def to_markdown(bp: Blueprint, secs: list[Section]) -> str:
    out = [f"# {bp.title}", "", f"_Exported from SPECForge on {datetime.now(UTC):%Y-%m-%d}_", ""]
    for s in secs:
        out += [f"## {s.title}", ""]
        out += [p + "\n" for p in s.paragraphs]
        out += [f"- {b}" for b in s.bullets]
        if s.bullets:
            out.append("")
        if s.table:

            def cell(x: str) -> str:
                return x.replace("|", "\\|").replace("\n", " ")

            out.append("| " + " | ".join(s.table[0]) + " |")
            out.append("|" + "---|" * len(s.table[0]))
            out += ["| " + " | ".join(cell(c) for c in row) + " |" for row in s.table[1:]]
            out.append("")
    return "\n".join(out).rstrip() + "\n"


def to_pdf(bp: Blueprint, secs: list[Section]) -> bytes:
    def escape(text: str) -> str:  # ReportLab paragraphs use XML-like markup
        return html.escape(text, quote=False)

    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import getSampleStyleSheet
    from reportlab.lib.units import mm
    from reportlab.platypus import (
        ListFlowable,
        ListItem,
        Paragraph,
        SimpleDocTemplate,
        Spacer,
        Table,
        TableStyle,
    )

    styles = getSampleStyleSheet()
    small = styles["BodyText"].clone("small", fontSize=8, leading=10)
    buf = io.BytesIO()
    doc = SimpleDocTemplate(
        buf,
        pagesize=A4,
        leftMargin=15 * mm,
        rightMargin=15 * mm,
        topMargin=15 * mm,
        bottomMargin=15 * mm,
        title=bp.title,
        author="SPECForge",
    )
    flow: list[Any] = [Paragraph(escape(bp.title), styles["Title"])]

    def md_inline(text: str) -> str:
        parts = escape(text).split("**")
        return "".join(f"<b>{p}</b>" if i % 2 else p for i, p in enumerate(parts)).replace(
            "\n", "<br/>"
        )

    for s in secs:
        flow.append(Paragraph(escape(s.title), styles["Heading2"]))
        flow += [Paragraph(md_inline(p), styles["BodyText"]) for p in s.paragraphs]
        if s.bullets:
            flow.append(
                ListFlowable(
                    [ListItem(Paragraph(md_inline(b), small)) for b in s.bullets],
                    bulletType="bullet",
                    leftIndent=10,
                )
            )
        if s.table:
            data = [[Paragraph(f"<b>{escape(c)}</b>", small) for c in s.table[0]]]
            data += [[Paragraph(escape(c), small) for c in row] for row in s.table[1:]]
            t = Table(data, repeatRows=1, hAlign="LEFT")
            t.setStyle(
                TableStyle(
                    [
                        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#eef2ff")),
                        ("GRID", (0, 0), (-1, -1), 0.25, colors.HexColor("#c7d2fe")),
                        ("VALIGN", (0, 0), (-1, -1), "TOP"),
                    ]
                )
            )
            flow.append(t)
        flow.append(Spacer(1, 4 * mm))
    doc.build(flow)
    return buf.getvalue()
