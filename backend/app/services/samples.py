"""Curated sample blueprints and the shared demo sandbox.

The four samples in app/llm/demo_data/ were generated by a real LLM run and
reviewed. They're copied into the Sandbox project so a visitor who clicks
"Try it instantly" sees complete, verified blueprints immediately, with no
LLM call and no waiting.

`reset_sandbox` (nightly Celery beat job, and `python -m app.seed`) wipes
everything visitors did in the sandbox and restores the samples.
"""

import logging
from typing import Any

from sqlalchemy import delete, select
from sqlalchemy.orm import Session

from app.core.errors import NotFound
from app.llm.providers.demo import load_samples
from app.llm.schemas import BlueprintDraft, to_graph
from app.models import Blueprint, Project
from app.models.enums import BlueprintStatus
from app.services import auth_service, graph

log = logging.getLogger("specforge.samples")


def list_samples() -> list[dict[str, Any]]:
    out = []
    for s in load_samples():
        d = BlueprintDraft.model_validate(s["draft"])
        nodes, edges = to_graph(d)
        out.append(
            {
                "slug": s["slug"],
                "title": s["title"],
                "brief": s["brief"],
                "generated_by": s.get("generated_by", "llm"),
                "nodes": len(nodes),
                "edges": len(edges),
            }
        )
    return out


def create_from_sample(db: Session, project: Project, slug: str) -> Blueprint:
    sample = next((s for s in load_samples() if s["slug"] == slug), None)
    if sample is None:
        raise NotFound(f"No sample called {slug}")
    bp = Blueprint(
        project_id=project.id,
        title=sample["title"],
        brief=sample["brief"],
        status=BlueprintStatus.ready,
        provider=f"sample ({sample.get('generated_by')})",
        is_sample=True,
        settings={"sample": slug},
    )
    db.add(bp)
    db.commit()
    nodes, edges = to_graph(BlueprintDraft.model_validate(sample["draft"]))
    graph.replace_graph(db, bp, nodes, edges)
    return bp


def sandbox_project(db: Session) -> Project:
    project = db.scalar(select(Project).where(Project.is_sandbox.is_(True)))
    if project is None:
        raise NotFound("Sandbox project missing")
    return project


def ensure_sandbox_samples(db: Session) -> list[Blueprint]:
    """If the sandbox is empty (fresh install, or a visitor deleted everything),
    restore the samples immediately. Returns the blueprints that were created,
    so the caller can queue their verification."""
    sandbox = sandbox_project(db)
    if db.scalar(select(Blueprint.id).where(Blueprint.project_id == sandbox.id).limit(1)):
        return []
    return [create_from_sample(db, sandbox, s["slug"]) for s in load_samples()]


def reset_sandbox(db: Session, *, verify: bool = True) -> dict[str, Any]:
    """Delete every sandbox blueprint and restore the curated samples (verified)."""
    auth_service.ensure_demo_user(db)
    sandbox = sandbox_project(db)
    removed = len(db.scalars(select(Blueprint.id).where(Blueprint.project_id == sandbox.id)).all())
    db.execute(delete(Blueprint).where(Blueprint.project_id == sandbox.id))
    db.commit()
    created = []
    for s in load_samples():
        bp = create_from_sample(db, sandbox, s["slug"])
        if verify:
            from app.services.verification import run_verification

            run_verification(db, bp)
        created.append({"slug": s["slug"], "id": str(bp.id), "score": bp.quality_score})
    log.info("sandbox reset: removed %s blueprints, restored %d samples", removed, len(created))
    return {"removed": removed, "samples": created}
